using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Hcoona.Nanopass.Generators;

internal sealed class LanguageEmitter(LanguageModel model)
{
    private const string Runtime = "global::Hcoona.Nanopass.";
    private const string SystemNamespace = "global::System.";
    private static readonly string[] FixedStaticMemberNames =
    [
        "Grammar", "Descriptor", "ToSExpression", "DiffTo", "Prune", "Parse", "Unparse",
        "UnparseObject", "UnparseToString", "CountNodes", "IsLanguageTerm", "Equals",
        "ReferenceEquals", "GetHashCode", "GetType", "ToString", "MemberwiseClone",
    ];

    private readonly StringBuilder source = new();
    private int indentation;

    internal static IEnumerable<string> StaticMemberNames(IEnumerable<string> nonTerminals) =>
        FixedStaticMemberNames.Concat(
            nonTerminals.SelectMany(static name => new[] { "Parse" + name, "Is" + name }));

    internal static IEnumerable<string> CaseTypes(
        LanguageModel model, LanguageModel.NonTerminal nonTerminal) =>
        nonTerminal.Productions.Select(rule => rule.Alternative is null
            ? model.QualifiedName + "." + Path(rule.RecordPath)
            : TargetType(model, rule.Alternative)).Distinct(StringComparer.Ordinal);

    internal static string Id(string name) =>
        SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    internal string Emit()
    {
        this.Line("// <auto-generated/>");
        this.Line("#nullable enable");
        this.Line("#pragma warning disable CA1716, CA1720, CS1591");
        if (model.Namespace.Length > 0)
        {
            this.Line($"namespace {model.Namespace};");
        }

        foreach (string container in model.Containers)
        {
            this.Open(container);
        }

        this.Line($"[{Runtime}LanguageMetadata({Literal(LanguageMetadataCodec.Encode(model))})]");
        this.Open($"{model.Accessibility} static partial class {Id(model.Name)}");
        this.EmitDescriptor();
        this.EmitRuntime();
        this.EmitApi();
        foreach (var nonTerminal in model.NonTerminals)
        {
            this.EmitNonTerminal(nonTerminal);
            foreach (var rule in nonTerminal.Productions)
            {
                if (rule.Alternative is null && !rule.IsDeclared
                    && rule.RecordPath.IndexOf('.') < 0)
                {
                    this.EmitRecord(rule);
                }
            }
        }

        this.Close();
        foreach (string _ in model.Containers)
        {
            this.Close();
        }

        return this.source.ToString();
    }

    private static string Literal(string? text) =>
        text is null ? "null" : SymbolDisplay.FormatLiteral(text, quote: true);

    private static string Path(string path) => string.Join(".", path.Split('.').Select(Id));

    private static string TargetType(LanguageModel model, LanguageModel.Field field) =>
        field.IsNonTerminal
            ? model.QualifiedName + "." + Id(field.Target)
            : model.Terminals.First(terminal =>
                string.Equals(terminal.Name, field.Target, StringComparison.Ordinal)).Type;

    private static string Number(int number) => number.ToString(CultureInfo.InvariantCulture);

    private static string Flag(bool value) => value ? "true" : "false";

    private static string UnionValue(LanguageModel.NonTerminal nonTerminal) =>
        UsesCustomUnion(nonTerminal) ? "RawValue" : "Value";

    private static bool UsesCustomUnion(LanguageModel.NonTerminal nonTerminal) =>
        nonTerminal.Declared == LanguageModel.Declaration.Struct
        || string.Equals(nonTerminal.Name, "Value", StringComparison.Ordinal);

    private static string TryGetValue(string type) =>
        "bool TryGetValue([global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] "
        + $"out {type} value)";

    private static string Datum(string? syntax) =>
        syntax is null ? "null" : $"{Runtime}SExpr.Parse({Literal(syntax)})";

    private static string Symbols(EquatableArray<string> symbols) =>
        "[" + string.Join(", ", symbols.Select(Literal)) + "]";

    private static string References(
        EquatableArray<LanguageModel.Field> fields, bool isNonTerminal) =>
        "[" + string.Join(", ", fields.Where(field => field.IsNonTerminal == isNonTerminal)
            .Select(static field => field.Target).Distinct(StringComparer.Ordinal).Select(Literal))
        + "]";

    private static string TerminalBinding(LanguageModel.Terminal terminal) =>
        "__NanopassTerminal_" + BindingKey(terminal.Name);

    private static string PrettyBinding(LanguageModel.Handler handler) =>
        "__NanopassPretty_" + BindingKey(handler.Name);

    private static string BindingKey(string name) =>
        Convert.ToBase64String(Encoding.UTF8.GetBytes(name))
            .Replace("=", string.Empty).Replace("/", "_Slash").Replace("+", "_Plus");

    private static string FieldType(string type, int depth, bool maybe)
    {
        string inner = maybe ? type + "?" : type;
        for (int i = 0; i < depth; i++)
        {
            inner = $"{Runtime}Seq<{inner}>";
        }

        return inner;
    }

    private static string ConvertField(string expression, string type, int depth, bool maybe)
    {
        if (depth == 0)
        {
            return $"({FieldType(type, 0, maybe)}){expression}" + (maybe ? string.Empty : "!");
        }

        var variable = "item" + Number(depth);
        return $"{Runtime}LanguageRuntime.Sequence({expression}, static {variable} => "
            + $"{ConvertField(variable, type, depth - 1, maybe)})";
    }

    private void EmitDescriptor()
    {
        this.Line($"public static {Runtime}LanguageDescriptor Descriptor {{ get; }} = new(");
        this.indentation++;
        this.Line($"{Literal(model.Name)}, {Literal(model.Entry)},");
        this.Open("[", null);
        foreach (var terminal in model.Terminals)
        {
            this.Line($"new({Literal(terminal.Name)}, {Symbols(terminal.MetaVars)}, "
                + $"typeof({terminal.Type}), {Literal(terminal.Predicate)}, "
                + $"{Datum(terminal.Prettifier)}),");
        }

        this.Close("],");
        this.Open("[", null);
        foreach (var nonTerminal in model.NonTerminals)
        {
            this.Line($"new({Literal(nonTerminal.Name)}, {Symbols(nonTerminal.MetaVars)},");
            this.Open("[", null);
            foreach (var rule in nonTerminal.Productions)
            {
                var name = rule.Alternative is null ? rule.Name : null;
                var fields = rule.Alternative is null ? rule.Fields : new([rule.Alternative]);
                var terminals = References(fields, isNonTerminal: false);
                var nonTerminals = References(fields, isNonTerminal: true);
                this.Line($"new({Datum(rule.Syntax)}, {Literal(name)}, "
                    + $"{Datum(rule.Pretty ?? rule.PrettyHandler?.Name)}) "
                    + $"{{ ReferencedTerminals = {terminals}, "
                    + $"ReferencedNonTerminals = {nonTerminals} }},");
            }

            this.Close("]),");
        }

        this.Close("]);");
        this.indentation--;
    }

    private void EmitRuntime()
    {
        this.Line($"private static {Runtime}LanguageRuntime Grammar {{ get; }} = "
            + $"new({Literal(model.Name)},");
        this.indentation++;
        this.Open("[", null);
        foreach (var terminal in model.Terminals)
        {
            this.Line($"{terminal.Owner}.{TerminalBinding(terminal)}(),");
        }

        this.Close("],");
        this.Open("[", null);
        foreach (var nonTerminal in model.NonTerminals)
        {
            string name = Id(nonTerminal.Name);
            var value = UnionValue(nonTerminal);
            this.Line($"new({Literal(nonTerminal.Name)}, typeof({name}), "
                + $"static ir => (({name})ir).{value},");
            this.Open("[", null);
            foreach (var rule in this.OrderRules(nonTerminal))
            {
                this.EmitRule(nonTerminal, rule);
            }

            this.Close("]),");
        }

        this.Close("]);");
        this.indentation--;

        foreach (var terminal in model.Terminals.Where(terminal =>
            string.Equals(terminal.Owner, model.QualifiedName, StringComparison.Ordinal)))
        {
            this.Line($"[{SystemNamespace}ComponentModel.EditorBrowsable("
                + $"{SystemNamespace}ComponentModel.EditorBrowsableState.Never)]");
            this.Line($"public static {Runtime}LanguageRuntime.Terminal "
                + $"{TerminalBinding(terminal)}() => new(");
            this.indentation++;
            var predicate = terminal.Predicate is null ? string.Empty : ", " + terminal.Predicate;
            var acceptance = terminal.Predicate is null ? "_" : "value";
            var condition = terminal.Predicate is null
                ? string.Empty
                : $" && {terminal.Predicate}(value)";
            var print = terminal.Prettifier is null
                ? "ir"
                : $"{terminal.Prettifier}(({terminal.Type})ir)";
            this.Line($"static datum => "
                + $"{Runtime}LanguageRuntime.ReadTerminal<{terminal.Type}>(datum{predicate}),");
            this.Line($"static ir => ir is {terminal.Type} {acceptance}{condition},");
            this.Line($"static ir => {Runtime}SExpr.FromValue({print}));");
            this.indentation--;
        }

        var handlers = model.NonTerminals.SelectMany(static nonTerminal => nonTerminal.Productions)
            .Select(static rule => rule.PrettyHandler).OfType<LanguageModel.Handler>()
            .Where(handler =>
                string.Equals(handler.Owner, model.QualifiedName, StringComparison.Ordinal))
            .Distinct();
        foreach (var handler in handlers)
        {
            this.Line($"[{SystemNamespace}ComponentModel.EditorBrowsable("
                + $"{SystemNamespace}ComponentModel.EditorBrowsableState.Never)]");
            this.Line($"public static {Runtime}SExpr {PrettyBinding(handler)}"
                + $"({Runtime}SExpr datum) => {handler.Name}(datum);");
        }
    }

    private void EmitRule(LanguageModel.NonTerminal nonTerminal, LanguageModel.Production rule)
    {
        string name = Id(nonTerminal.Name);
        string syntax = Literal(rule.Syntax);
        string pretty = Literal(rule.Pretty);
        if (rule.Alternative is { } alternative)
        {
            this.Line($"new({syntax}, {pretty}, {this.Field(alternative)}, [], null, "
                + $"static fields => ({name})({this.TargetType(alternative)})fields[0]!, null),");
            return;
        }

        string type = Path(rule.RecordPath);
        var args = string.Join(", ", rule.Fields.Select((field, index) =>
            Id(field.Property) + ": " + ConvertField(
                $"fields[{Number(index)}]",
                this.TargetType(field),
                field.SequenceDepth,
                field.IsMaybe)));
        var reads = string.Join(", ", rule.Fields.Select(
            field => $"(({type})ir).{Id(field.Property)}"));
        var fields = string.Join(", ", rule.Fields.Select(this.Field));
        var handler = rule.PrettyHandler is { } custom
            ? $", {custom.Owner}.{PrettyBinding(custom)}"
            : string.Empty;
        this.Line($"new({syntax}, {pretty}, null, [{fields}], typeof({type}),");
        this.indentation++;
        this.Line($"static fields => ({name})new {type}({args}), "
            + $"static ir => [{reads}]{handler}),");
        this.indentation--;
    }

    private void EmitApi()
    {
        string entry = Id(model.Entry);
        this.Line($"public static {entry} Parse({Runtime}SExpr datum) "
            + $"=> Parse{model.Entry}(datum);");
        this.Line($"public static {entry} Parse(string text) => Parse{model.Entry}(text);");
        this.Line($"public static {Runtime}SExpr UnparseObject(object? ir, bool raw = false) "
            + "=> Grammar.Unparse(ir, raw);");
        this.Line("public static int CountNodes(object? ir) => Grammar.CountNodes(ir);");
        this.Line("public static bool IsLanguageTerm(object? ir) => Grammar.IsTerm(ir);");
        this.Line($"public static {Runtime}SExpr ToSExpression(bool includePrettifiers = false) "
            + $"=> {Runtime}LanguageServices.ToSExpression(Descriptor, includePrettifiers);");
        this.Line($"public static {Runtime}SExpr DiffTo({Runtime}LanguageDescriptor target) "
            + $"=> {Runtime}LanguageServices.Diff(Descriptor, target);");
        this.Line($"public static {Runtime}SExpr Prune() "
            + $"=> {Runtime}LanguageServices.Prune(Descriptor);");

        for (int index = 0; index < model.NonTerminals.Count; index++)
        {
            string name = model.NonTerminals[index].Name;
            string type = Id(name);
            this.Line($"public static {type} Parse{name}({Runtime}SExpr datum) "
                + $"=> ({type})Grammar.Parse({Number(index)}, datum);");
            this.Line($"public static {type} Parse{name}(string text) "
                + $"=> Parse{name}({Runtime}SExpr.Parse(text));");
            this.Line($"public static {Runtime}SExpr Unparse({type} ir, bool raw = false) "
                + "=> Grammar.Unparse(ir, raw);");
            this.Line($"public static string UnparseToString({type} ir, bool raw = false) "
                + "=> Unparse(ir, raw).Format();");
            this.Line($"public static int CountNodes({type} ir) => Grammar.CountNodes(ir);");
            this.Line($"public static bool Is{name}(object? ir) "
                + $"=> Grammar.IsTerm({Number(index)}, ir);");
        }
    }

    private void EmitNonTerminal(LanguageModel.NonTerminal nonTerminal)
    {
        string name = Id(nonTerminal.Name);
        if (UsesCustomUnion(nonTerminal))
        {
            this.Line($"[{SystemNamespace}Runtime.CompilerServices.Union]");
            this.Open($"public readonly partial struct {name} : {name}.IUnionMembers, "
                + $"{SystemNamespace}IEquatable<{name}>");
            this.EmitUnionMembers(nonTerminal);
        }
        else
        {
            var cases = nonTerminal.Declared == LanguageModel.Declaration.None
                ? $"({string.Join(", ", CaseTypes(model, nonTerminal))})"
                : string.Empty;
            this.Open($"public partial union {name}{cases} : {SystemNamespace}IEquatable<{name}>");
        }

        var value = UnionValue(nonTerminal);
        this.Line($"public bool Equals({name} other) "
            + $"=> object.Equals(this.{value}, other.{value});");
        this.Line("public override bool Equals(object? other) "
            + $"=> other is {name} value && this.Equals(value);");
        this.Line($"public override int GetHashCode() => this.{value}?.GetHashCode() ?? 0;");
        this.Line($"public static bool operator ==({name} left, {name} right) "
            + "=> left.Equals(right);");
        this.Line($"public static bool operator !=({name} left, {name} right) "
            + "=> !left.Equals(right);");
        foreach (var rule in nonTerminal.Productions)
        {
            if (rule.Alternative is null && !rule.IsDeclared && rule.RecordPath.IndexOf('.') >= 0)
            {
                this.EmitRecord(rule);
            }
        }

        this.Close();
    }

    private void EmitUnionMembers(LanguageModel.NonTerminal nonTerminal)
    {
        string name = Id(nonTerminal.Name);
        var types = CaseTypes(model, nonTerminal).ToArray();
        this.Line("private readonly object? storedValue;");
        this.Line($"private {name}(object? value) => this.storedValue = value;");
        this.Line("public object? RawValue => this.storedValue;");
        this.Line("object? IUnionMembers.Value => this.storedValue;");
        this.Line("bool IUnionMembers.HasValue => this.storedValue is not null;");
        foreach (var type in types)
        {
            this.Line($"static {name} IUnionMembers.Create({type} value) => new((object)value);");
            this.Open($"public {TryGetValue(type)}");
            this.Line($"if (this.storedValue is {type} typed) {{ value = typed; return true; }}");
            this.Line("value = default;");
            this.Line("return false;");
            this.Close();
        }

        this.Open("public interface IUnionMembers");
        this.Line("object? Value { get; }");
        this.Line("bool HasValue { get; }");
        foreach (var type in types)
        {
            this.Line($"static abstract {name} Create({type} value);");
            this.Line($"{TryGetValue(type)};");
        }

        this.Close();
    }

    private void EmitRecord(LanguageModel.Production production)
    {
        var lastDot = production.RecordPath.LastIndexOf('.');
        var name = Id(production.RecordPath.Substring(lastDot + 1));
        string fields = string.Join(", ", production.Fields.Select(
            field => FieldType(this.TargetType(field), field.SequenceDepth, field.IsMaybe)
                + " " + Id(field.Property)));
        this.Line($"public sealed record {name}({fields});");
    }

    private IEnumerable<LanguageModel.Production> OrderRules(
        LanguageModel.NonTerminal nonTerminal) =>
            nonTerminal.Productions.OrderBy(rule => rule.Alternative switch
        {
            { IsNonTerminal: true } field => this.HasImplicit(field.Target, []) ? 4 : 0,
            { IsNonTerminal: false } => 2,
            _ => rule.IsImplicit ? 3 : 1,
        });

    private bool HasImplicit(string target, HashSet<string> visited)
    {
        if (!visited.Add(target))
        {
            return false;
        }

        var nonTerminal = model.NonTerminals.First(item =>
            string.Equals(item.Name, target, StringComparison.Ordinal));
        return nonTerminal.Productions.Any(rule => rule.IsImplicit
            || (rule.Alternative is { IsNonTerminal: true } alt
                && this.HasImplicit(alt.Target, visited)));
    }

    private string TargetType(LanguageModel.Field field) => TargetType(model, field);

    private string Field(LanguageModel.Field field)
    {
        int index = field.IsNonTerminal
            ? model.NonTerminals.TakeWhile(item =>
                !string.Equals(item.Name, field.Target, StringComparison.Ordinal)).Count()
            : model.Terminals.TakeWhile(item =>
                !string.Equals(item.Name, field.Target, StringComparison.Ordinal)).Count();
        return $"new {Runtime}LanguageRuntime.Field({Literal(field.MetaVar)}, {Number(index)}, "
            + $"{Flag(field.IsNonTerminal)}, {Number(field.SequenceDepth)}, {Flag(field.IsMaybe)})";
    }

    private void Line(string text) =>
        this.source.Append(' ', this.indentation * 4).Append(text).Append('\n');

    private void Open(string text, string? brace = "{")
    {
        this.Line(text);
        if (brace is not null)
        {
            this.Line(brace);
        }

        this.indentation++;
    }

    private void Close(string brace = "}")
    {
        this.indentation--;
        this.Line(brace);
    }
}
