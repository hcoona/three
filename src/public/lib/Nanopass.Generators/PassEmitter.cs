using System;
using System.Globalization;
using System.Linq;
using System.Text;

using static Hcoona.Nanopass.Generators.PassInputReader;
using static Hcoona.Nanopass.Generators.PassResolver;

namespace Hcoona.Nanopass.Generators;

internal sealed class PassEmitter(PassModel model)
{
    private const string Failure = "throw new " + Runtime
        + "NanopassException(\"The pass has no applicable transformation.\");";

    private readonly StringBuilder source = new();
    private readonly string title = Literal(model.Declaration.Name);
    private int depth;

    internal string Emit()
    {
        this.Line("// <auto-generated/>");
        this.Line("#nullable enable");
        this.Line("#pragma warning disable CS1591");
        var declaration = model.Declaration;
        if (declaration.Namespace.Length > 0)
        {
            this.Line($"namespace {declaration.Namespace};");
        }

        foreach (var container in declaration.Containers)
        {
            this.Open(container);
        }

        var input = model.InputKind is null ? null : Type(model.InputKind.Type);
        var output = model.OutputKind is null ? null : Type(model.OutputKind.Type);
        bool hasEndpoints = input is not null && output is not null;
        bool hasAdapter = model.Problems.Count > 0 || model.InterfaceCall is not null;
        string? passInterface = hasEndpoints && hasAdapter
            ? $"{Runtime}IPass<{input}, {output}>"
            : null;
        string interfaces = !hasEndpoints
            ? string.Empty
            : $" : {Runtime}INanopassPass, {Runtime}INanopassPassMetadata"
                + (passInterface is null ? string.Empty : $", {passInterface}");
        this.Open($"{declaration.Accessibility} partial class {Id(declaration.Name)}{interfaces}");
        if (input is not null && output is not null)
        {
            this.EmitDescriptor();
            this.EmitRun(input, output, passInterface);
        }
        else if (model.Run is { IsPartialDeclaration: true } run)
        {
            this.EmitStub(run);
        }

        if (model.Problems.Count > 0)
        {
            foreach (var method in model.Declaration.Methods.Where(method =>
                method.IsPartialDeclaration && method != model.Run
                && (method.Processor is not null || method.Rewrites.Count > 0
                    || method.Name == "Run")))
            {
                this.EmitStub(method);
            }
        }
        else
        {
            foreach (var processor in model.Processors.Where(static item => item.IsSynthesized))
            {
                this.EmitProcessor(processor);
            }
        }

        this.Close();
        foreach (var _ in declaration.Containers)
        {
            this.Close();
        }

        return this.source.ToString();
    }

    private static string Number(int number) => number.ToString(CultureInfo.InvariantCulture);

    private static string Signature(PassInput.Method method)
    {
        string staticModifier = method.IsStatic ? "static " : string.Empty;
        string typeParameters = method.TypeParameters.Count == 0
            ? string.Empty
            : "<" + string.Join(", ", method.TypeParameters.Select(Id)) + ">";
        string parameters = string.Join(", ", method.Parameters.Select(static parameter =>
            $"{parameter.Modifier}{Type(parameter.Type)} {Id(parameter.Name)}"));
        return $"{method.Accessibility} {staticModifier}partial "
            + $"{method.ReturnModifier}{Type(method.ReturnType)} "
            + $"{Id(method.Name)}{typeParameters}({parameters})";
    }

    private static string SymbolLiteral(string kind) =>
        string.Equals(kind, "*", StringComparison.Ordinal)
            ? "null"
            : $"new {Runtime}Symbol({Literal(kind)})";

    private void EmitStub(PassInput.Method method)
    {
        this.Open(Signature(method));
        this.Line(Failure);
        this.Close();
    }

    private void EmitDescriptor()
    {
        var input = model.InputKind!;
        var output = model.OutputKind!;
        string? from = model.SourceLanguage?.QualifiedName;
        string? to = model.TargetLanguage?.QualifiedName;
        string descriptor = Runtime + "PassDescriptor";
        this.Line("/// <summary>Gets the descriptor for this pass.</summary>");
        this.Line($"public static {descriptor} PassDescriptor {{ get; }} = new(");
        this.depth++;
        this.Line($"new {Runtime}Symbol({this.title}),");
        var inputDescriptor = from is null ? "null" : from + ".Descriptor";
        var outputDescriptor = to is null ? "null" : to + ".Descriptor";
        this.Line($"{inputDescriptor}, {SymbolLiteral(input.Name)},");
        this.Line($"{outputDescriptor}, {SymbolLiteral(output.Name)},");
        this.Open(string.Empty, "[");
        foreach (var processor in model.Processors)
        {
            int extras = processor.Result.IsTuple ? processor.Result.Arguments.Count - 1 : 0;
            this.Line($"new(new {Runtime}Symbol({Literal(processor.Name)}), "
                + $"{SymbolLiteral(processor.From.Name)}, {SymbolLiteral(processor.To.Name)}, "
                + $"{Number(processor.Parameters.Count)}, {Number(extras)}),");
        }

        this.Close("],");
        this.Line(from is null ? "null," : $"static datum => {from}.Parse{input.Name}(datum),");
        this.Line(to is null
            ? "null);"
            : $"static (value, raw) => {to}.UnparseObject(value, raw));");
        this.depth--;
        this.Line($"{descriptor} {Runtime}INanopassPass.Descriptor => PassDescriptor;");
    }

    private void EmitRun(string input, string output, string? passInterface)
    {
        var run = model.Run;
        bool valid = model.Problems.Count == 0;
        string inputName = run?.Parameters.Count > 0
            ? Id(run.Parameters[0].Name)
            : InputVariable;
        if (run is null || run.IsPartialDeclaration)
        {
            if (run is null)
            {
                this.Line("/// <summary>Transforms the input term.</summary>");
                this.Line($"/// <param name=\"{inputName}\">The term to transform.</param>");
                this.Line("/// <returns>The transformed term.</returns>");
            }

            string header = run is null
                ? $"public {output} Run({input} {inputName})"
                : Signature(run);
            this.Open(header);
            if (valid && model.EntryCall is { } call)
            {
                var parameters = run?.Parameters ?? default;
                string trace = Local(parameters, "__np_trace");
                if (model.Declaration.Trace)
                {
                    this.Line($"bool {trace} = {Runtime}PassTrace.BeginStage(this);");
                }

                this.Trace(null, "Enter", inputName, trace);
                this.EmitReturn(call, null, output, Local(parameters, "__np_result"), trace);
            }
            else
            {
                this.Line(Failure);
            }

            this.Close();
        }

        if (run is not null && passInterface is not null)
        {
            var interfaceCall = valid ? model.InterfaceCall : null;
            this.Line($"{output} {passInterface}.Run({input} {InputVariable}) => "
                + (interfaceCall is null ? Failure : interfaceCall + ";"));
        }

        if (!model.Declaration.MemberNames.Contains("Visit", StringComparer.Ordinal)
            && (run is null || (run.IsPartialDeclaration && model.InterfaceCall is not null)))
        {
            var visit = valid ? model.InterfaceCall : null;
            this.Line($"private {output} Visit({input} {InputVariable}) => "
                + (visit is null ? Failure : visit + ";"));
        }
    }

    private void EmitProcessor(PassModel.Processor processor)
    {
        var method = processor.Method;
        var ir = method is null ? InputVariable : Id(method.Parameters[0].Name);
        string parameters = string.Join(string.Empty, processor.Parameters.Select(parameter =>
            $", {Type(parameter.Type)} {Id(parameter.Name)}"));
        var resultType = Type(processor.Result);
        var signature = method is not null
            ? Signature(method)
            : $"private {resultType} {Id(processor.Name)}"
                + $"({Type(processor.From.Type)} {ir}{parameters})";
        this.Open(signature);
        var allParameters = method?.Parameters ?? processor.Parameters;
        if (processor.Defaults.Count > 0 && !processor.Alternatives.Any(
            static alternative => alternative.Fallback is { UsesDefaults: true }))
        {
            // Bind the defaults without evaluating their conversions at runtime.
            string check = Local(allParameters, "__np_checkDefaults");
            this.Line($"static {resultType} {check}() => "
                + $"(default!, {string.Join(", ", processor.Defaults)});");
            this.Line($"_ = nameof({check});");
        }

        this.Trace(processor.Name, "Enter", ir);
        if (processor.Alternatives.Any(static alternative => alternative.Condition is not null))
        {
            string value = LanguageEmitter.UnionValue(
                processor.From.NonTerminal!, Type(processor.From.Type), ir);
            this.Line($"var {Local(allParameters, "__np_val")} = {value};");
        }

        string result = Local(allParameters, "__np_result");
        bool returned = false;
        foreach (var alternative in processor.Alternatives)
        {
            if (alternative.Condition is { } expression)
            {
                this.Open(string.Empty);
                this.Open($"if ({expression})");
            }

            var handled = false;
            foreach (var (guard, call) in alternative.Rewrites)
            {
                if (guard is null)
                {
                    this.EmitReturn(call, processor.Name, resultType, result);
                    handled = true;
                    break;
                }

                this.Open($"if ({guard})");
                this.EmitReturn(call, processor.Name, resultType, result);
                this.Close();
            }

            if (!handled && alternative.Fallback is { } fallback)
            {
                if (fallback.Subprocessor is { } subprocessor)
                {
                    this.Line($"var {subprocessor.Variable} = {subprocessor.Call};");
                }

                this.EmitReturn(fallback.Expression, processor.Name, resultType, result);
                handled = true;
            }

            if (alternative.Condition is null)
            {
                returned = handled;
            }
            else
            {
                this.Close();
                this.Close();
            }
        }

        if (!returned)
        {
            this.Line(Failure);
        }

        this.Close();
    }

    private void EmitReturn(
        string expression,
        string? processor,
        string resultType,
        string result,
        string? trace = null)
    {
        if (model.Declaration.Trace)
        {
            this.Open(string.Empty);
            this.Line($"{resultType} {result} = {expression};");
            this.Trace(processor, "Exit", result, trace);
            this.Line($"return {result};");
            this.Close();
        }
        else
        {
            this.Line($"return {expression};");
        }
    }

    private void Trace(string? processor, string phase, string value, string? trace = null)
    {
        if (model.Declaration.Trace)
        {
            this.Line($"if ({trace ?? Runtime + "PassTrace.IsEnabled"}) "
                + $"{Runtime}PassTrace.Emit(new("
                + $"{this.title}, {(processor is null ? "null" : Literal(processor))}, "
                + $"{Runtime}PassTracePhase.{phase}, {value}, PassDescriptor));");
        }
    }

    private void Line(string text) => this.source.Append(' ', this.depth * 4).AppendLine(text);

    private void Open(string text, string brace = "{")
    {
        if (text.Length > 0)
        {
            this.Line(text);
        }

        this.Line(brace);
        this.depth++;
    }

    private void Close(string brace = "}")
    {
        this.depth--;
        this.Line(brace);
    }
}
